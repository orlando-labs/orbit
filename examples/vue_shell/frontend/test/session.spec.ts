import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('application assets stream through Sputnik with GET and HEAD', async ({ request }) => {
  const expected = await readFile('../assets/favicon.svg', 'utf8')
  const icon = await request.get('/favicon.svg')
  expect(icon.status()).toBe(200)
  expect(await icon.text()).toBe(expected)
  expect(icon.headers()['content-type']).toBe('image/svg+xml')
  expect(icon.headers()['content-length']).toBe(String(Buffer.byteLength(expected)))
  expect(icon.headers()['transfer-encoding']).toBeUndefined()
  expect(icon.headers()['x-content-type-options']).toBe('nosniff')
  expect(icon.headers()['cache-control']).toBe('public, max-age=3600')
  expect(icon.headers()['set-cookie']).toBeUndefined()
  const head = await request.head('/favicon.svg')
  expect(head.status()).toBe(200)
  expect((await head.body()).length).toBe(0)
  expect(head.headers()['content-length']).toBe(icon.headers()['content-length'])
  expect((await request.get('/missing-asset.svg')).status()).toBe(404)
  expect((await request.get('/.env')).status()).toBe(404)
})

test('session URL negotiates HTML, JSON and a vendor MIME', async ({ page }) => {
  const html = await page.goto('/api/session')
  expect(html?.status()).toBe(200)
  expect(html?.headers()['content-type']).toContain('text/html')
  expect(html?.headers().vary.toLowerCase().split(',').map(value => value.trim())).toContain('accept')
  await expect(page.getByTestId('vue-account')).toBeVisible()
  for (const type of ['application/json', 'application/vnd.orbit.session+json']) {
    const response = await page.request.get('/api/session', { headers: { Accept: type } })
    expect(response.status()).toBe(200)
    expect(response.headers()['content-type']).toContain(type)
    expect((await response.json()).schema).toBe('orbit.vue-shell.v1')
    expect(response.headers()['cache-control']).toContain('no-store')
  }
  const unavailable = await page.request.get('/api/session', { headers: { Accept: 'image/png' } })
  expect(unavailable.status()).toBe(406)
  expect(unavailable.headers().vary).toContain('Accept')
  const invalid = await page.request.get('/api/session', { headers: { Accept: 'application/json;q=2' } })
  expect(invalid.status()).toBe(400)
  const home = await page.request.get('/', { headers: { Accept: 'application/json' } })
  expect((await home.json()).schema).toBe('orbit.vue-shell.v1')
  const csrf = (await page.context().cookies()).find(cookie => cookie.name === 'orbit-csrf')!.value
  const start = await page.request.post('/auth/github', { headers: { Accept: 'text/html', Origin: new URL(page.url()).origin, 'X-CSRF-Token': decodeURIComponent(csrf) }, maxRedirects: 0 })
  expect(start.status()).toBe(303)
  expect(new URL(start.headers().location).pathname).toBe('/login/oauth/authorize')
  const logout = await page.request.post('/auth/logout', { headers: { Accept: 'text/html', Origin: new URL(page.url()).origin, 'X-CSRF-Token': decodeURIComponent(csrf) }, maxRedirects: 0 })
  expect(logout.status()).toBe(303)
  expect(logout.headers().location).toBe('/')
})

test('GitHub flow, Vue account, reload, refresh and logout', async ({ page, context, browser }) => {
  const failures: string[] = []
  const hmrConnections: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  page.on('console', message => { if (message.type() === 'error') failures.push(message.text()) })
  page.on('websocket', socket => socket.on('framereceived', frame => {
    if (typeof frame.payload === 'string' && frame.payload === '{"type":"connected"}') hmrConnections.push(socket.url())
  }))
  const response = await page.goto('/')
  expect(response?.headers()['cache-control']).toContain('no-store')
  const csp = response!.headers()['content-security-policy']
  expect(csp).toContain("object-src 'none'")
  expect(csp).toContain("form-action 'self'")
  expect(csp).not.toContain('unsafe-eval')
  await expect(page.getByTestId('vue-account')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continue with GitHub' })).toBeVisible()
  const before = (await context.cookies()).find(cookie => cookie.name === 'orbit-csrf')?.value
  const shell = await response!.text()
  await expect(page).toHaveTitle('Orbit · Account')
  await expect(page.locator('main > #notebook-app[data-page="account"]')).toBeVisible()
  expect(shell).toContain('application/json')
  expect(shell).not.toContain('fixture-secret')
  expect(shell).not.toContain('code_verifier')
  const scripts = page.locator('head script[type="module"][src]')
  const sources = await scripts.evaluateAll(nodes => nodes.map(node => node.getAttribute('src')))
  if (process.env.ORBIT_E2E_MODE === 'development') {
    expect(sources).toHaveLength(2)
    expect(sources[0]).toMatch(/^http:\/\/127\.0\.0\.1:\d+\/@vite\/client$/)
    expect(sources[1]).toMatch(/^http:\/\/127\.0\.0\.1:\d+\/src\/main\.ts$/)
    const devOrigin = new URL(sources[0]!).origin
    expect(csp).toContain(`script-src 'self' ${devOrigin}`)
    expect(csp).toContain(`connect-src 'self' ${devOrigin} ${devOrigin.replace('http:', 'ws:')}`)
    await expect.poll(() => hmrConnections.length).toBeGreaterThan(0)
  } else {
    expect(sources).toHaveLength(1)
    expect(sources[0]).toMatch(/^\/assets\/main-[\w-]+\.js$/)
    await expect(page.locator('head link[rel="stylesheet"]')).toHaveCount(1)
    expect(csp).not.toContain('unsafe-inline')
    expect(csp).not.toMatch(/wss?:\/\//)
  }
  await page.getByRole('button', { name: 'Continue with GitHub' }).click()
  await page.getByRole('button', { name: 'Authorize Orbit preview' }).click()
  await expect(page.getByRole('heading', { name: 'Orbit Tester' })).toBeVisible()
  await expect(page.getByTestId('account-id')).toHaveText('9007199254740995')
  expect(page.url()).toBe(response!.url())
  const cookies = await context.cookies()
  expect(cookies.find(cookie => cookie.name === 'orbit-session')?.httpOnly).toBe(true)
  expect(cookies.find(cookie => cookie.name === 'orbit-session')?.sameSite).toBe('Lax')
  expect(cookies.find(cookie => cookie.name === 'orbit-csrf')?.value).not.toBe(before)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Orbit Tester' })).toBeVisible()
  await page.getByRole('button', { name: 'Refresh session' }).click()
  await expect(page.getByRole('button', { name: 'Refresh session' })).toBeEnabled()
  const api = await page.request.get('/api/session', { headers: { Accept: 'application/json' } })
  const body = await api.json()
  expect(body.account.uid).toBe('9007199254740995')
  expect(body.session.authenticated).toBe(true)
  expect(JSON.stringify(body)).not.toMatch(/access_token|client_secret|code_verifier|_orbit_oauth/)
  const guest = await browser.newContext()
  try {
    const other = await guest.request.get(new URL('/api/session', page.url()).href, { headers: { Accept: 'application/json' } })
    expect((await other.json()).account).toBeNull()
  } finally { await guest.close() }
  await page.screenshot({ path: `../../../build/vue-${process.env.ORBIT_E2E_MODE || 'production'}-account.png`, fullPage: true })
  const logoutResponse = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/auth/logout')
  await page.getByRole('button', { name: 'Sign out' }).click()
  const loggedOut = await logoutResponse
  expect(loggedOut.status()).toBe(204)
  expect(loggedOut.headers()['content-length']).toBeUndefined()
  expect(loggedOut.headers()['transfer-encoding']).toBeUndefined()
  await expect(page.getByRole('button', { name: 'Continue with GitHub' })).toBeVisible()
  expect((await (await page.request.get('/api/session', { headers: { Accept: 'application/json' } })).json()).account).toBeNull()
  expect(failures).toEqual([])
})

test('CSRF, invalid callback, denied login and missing assets', async ({ page }) => {
  await page.goto('/')
  expect((await page.request.post('/auth/github')).status()).toBe(403)
  expect((await page.request.post('/auth/logout', { headers: { Origin: 'https://untrusted.example' } })).status()).toBe(403)
  await page.goto('/auth/github/callback?code=invalid&state=' + 'a'.repeat(64))
  await expect(page.getByRole('alert')).toContainText('not completed')
  await expect(page.getByRole('button', { name: 'Continue with GitHub' })).toBeVisible()
  await page.getByRole('button', { name: 'Continue with GitHub' }).click()
  await page.getByRole('button', { name: 'Cancel authorization' }).click()
  await expect(page.getByRole('alert')).toContainText('not completed')
  expect((await (await page.request.get('/api/session', { headers: { Accept: 'application/json' } })).json()).account).toBeNull()
  const missing = await page.request.get('/assets/missing.js')
  expect(missing.status()).toBe(404)
  expect(await missing.text()).not.toContain('<html')
  expect((await page.request.get('/.vite/manifest.json')).status()).toBe(404)
})
